const createdAt = "2026-07-19";

function buildExpert(expert: {
  id: string;
  name: string;
  avatar: string;
  role: AgentConfig["role"];
  roleLabel: string;
  title: string;
  department: string;
  model: string;
  color: string;
  roleDescription: string;
  skills: string[];
  tools: string[];
  source: string;
  principles: string[];
  standards: string[];
  workflow: string[];
}): ExpertDefinition {
  return {
    config: {
      id: expert.id,
      name: expert.name,
      role: expert.role,
      roleLabel: expert.roleLabel,
      model: expert.role === "reviewer" ? "deepseek-v4-pro" : "deepseek-v4-flash",
      skills: expert.skills,
      tools: expert.tools,
      avatar: expert.avatar,
      color: expert.color,
    },
    profile: {
      id: expert.id,
      name: expert.name,
      avatar: expert.avatar,
      title: expert.title,
      department: expert.department,
      roleDescription: expert.roleDescription,
      model: expert.role === "reviewer" ? "deepseek-v4-pro" : "deepseek-v4-flash",
      color: expert.color,
      skills: expert.skills.slice(0, 5).map((name, index) => ({
        name,
        level: index < 2 ? 5 : 4,
        description: `来自 ${expert.source} 的专家能力摘要`,
      })),
      tools: expert.tools.map((name) => ({
        name,
        icon: name.includes("搜索") ? "🔍" : name.includes("代码") || name.includes("终端") ? "⚡" : name.includes("质量") ? "✅" : "📄",
        granted: true,
        description: "按任务需要调用的专家工具能力",
      })),
      memory: {
        longTerm: [
          `专家来源：${expert.source}`,
          "执行时只加载当前任务相关技能摘要，避免上下文过大",
        ],
        projectExperience: [],
        knowledge: expert.skills,
      },
      performance: {
        tasksCompleted: 0,
        projectsCount: 0,
        successRate: 100,
        rating: 4.5,
        recentProjects: [],
      },
      status: "IDLE",
      currentTask: null,
      createdAt,
    },
    constitution: {
      agentId: expert.id,
      workingPrinciples: expert.principles,
      decisionHabits: [
        "优先使用当前任务目标和 Workspace 上下文",
        "先输出结构化判断，再给出可执行方案",
        "任务过大时主动压缩范围并保留关键依据",
      ],
      outputStandards: expert.standards,
      prohibitions: [
        "禁止编造不存在的数据、来源或执行结果",
        "禁止绕过 Controller 指定的任务边界",
        "禁止把错误信息当作正常交付传递给下游",
      ],
      professionalWorkflow: expert.workflow.map((phase, index) => ({
        order: index + 1,
        phase,
        action: `${phase}当前任务`,
        check: `${phase}结果可被下游 Agent 使用`,
      })),
    },
  };
}

